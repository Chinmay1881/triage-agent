def call(tool: str, **args: Any) -> AIMessage:
    return AIMessage("", tool_calls=[{"name": tool, "args": args, "id": "x", "type": "tool_call"}])


def ref(text: str, tool: str) -> str:
    match = re.search(rf"tool:{tool}#\d+", text)
    if match is None:
        raise RuntimeError(f"no {tool} ref in the prompt")
    return match.group(0)


def reputation_ref(messages: Sequence[BaseMessage], indicator: str) -> str:
    """The ref the intel brief gives for one indicator, as a model would read it."""
    case = json.loads(str(messages[-2].content))
    rows = case["untrusted_log_data"]["intel_facts"]["reputation"]
    return next(r["ref"] for r in rows if r["indicator"] == indicator)


