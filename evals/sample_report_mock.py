async def main_async() -> int:
    settings = get_settings()
    alert_id = next(r.alert.alert_id for r in eval_week().scenarios if r.scenario_id == "s01")
    client = telemetry_client()
    try:
        db = telemetry_db(client)
        telemetry = MongoTelemetry(db)
        store = InMemoryStore()
        llm = MockLLM(script())
        tool = partial(call_tool, db=db)
        runner = Runner(store, telemetry, tool, settings, lambda _, __: llm)
        services = Services(store, telemetry, runner, settings, RESULTS)
        app = create_app(lambda: services)
        async with httpx.AsyncClient(
            transport=httpx.ASGITransport(app=app), base_url="http://sample"
        ) as api:
            started = await api.post("/investigations", json={"alert_id": alert_id})
            started.raise_for_status()
            investigation_id = started.json()["investigation_id"]
            await runner.tasks[investigation_id]
            url = f"/investigations/{investigation_id}"
            for body in (
                {"action_id": "A1", "decision": "approve", "note": "Finance confirmed no impact."},
                {"action_id": "A2", "decision": "approve"},
                {"action_id": "A3", "decision": "reject", "note": "Wait for the forensics."},
                {"verdict_decision": "agree", "note": "The chain matches the phishing report."},
            ):
                (await api.post(f"{url}/decision", json=body)).raise_for_status()
            report = await api.get(f"{url}/report.md")
            report.raise_for_status()
            status = (await api.get(url)).json()["status"]
    finally:
        await client.close()
    OUTPUT.write_text(HEADER + report.text, encoding="utf-8", newline="\n")
    print(f"status {status}; wrote {OUTPUT}")
    return 0


def main() -> int:
    if isinstance(sys.stdout, io.TextIOWrapper):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    return asyncio.run(main_async())


if __name__ == "__main__":
    sys.exit(main())
